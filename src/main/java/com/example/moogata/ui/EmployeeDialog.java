    private void btnOKActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnOKActionPerformed
        String name = txtLogin.getText().trim();
        String position = txtPosition.getText().trim();
        String password = new String(txtPassword.getPassword());

        if (name.isEmpty() || position.isEmpty() || password.isEmpty()) {
            JOptionPane.showMessageDialog(this,
                    "กรอกข้อมูลให้ครบทุกช่องก่อนบันทึก",
                    "ข้อมูลไม่ครบ", JOptionPane.WARNING_MESSAGE);
            return;
        }

        Employee emp = new Employee(name, position, password, getSelectedRole());

        if (employeeId > 0) {
            // โหมดแก้ไข — ใส่ id เดิมกลับเข้าไปก่อน update
            emp.setId(employeeId);
            if (employeeService.update(emp) == null) {
                JOptionPane.showMessageDialog(this,
                        "แก้ไขไม่สำเร็จ (ชื่อล็อกอินซ้ำกับคนอื่น หรือไม่พบแถวเดิม)",
                        "แก้ไขไม่สำเร็จ", JOptionPane.ERROR_MESSAGE);
                return;
            }
        } else {
            // โหมดเพิ่ม — save จะคืน object พร้อม id ใหม่ หรือ null ถ้าล้มเหลว
            if (employeeService.save(emp) == null) {
                JOptionPane.showMessageDialog(this,
                        "บันทึกไม่สำเร็จ (ชื่อล็อกอินซ้ำกับคนอื่น)",
                        "บันทึกไม่สำเร็จ", JOptionPane.ERROR_MESSAGE);
                return;
            }
        }

        saved = true;
        dispose();
    }//GEN-LAST:event_btnOKActionPerformed

