    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        int row = tblEmployee.getSelectedRow();
        if (row == -1) {
            JOptionPane.showMessageDialog(this,
                    "เลือกพนักงานในตารางก่อนกดลบ",
                    "ยังไม่ได้เลือก", JOptionPane.WARNING_MESSAGE);
            return;
        }
        int id = (Integer) tblEmployee.getValueAt(row, 0);
        String selectedName = (String) tblEmployee.getValueAt(row, 1);

        // กฎธุรกิจ: ห้ามลบบัญชีที่กำลังล็อกอินอยู่ (กันผู้จัดการลบตัวเองจนเข้าระบบไม่ได้)
        if (selectedName.equals(loginUser.getName())) {
            JOptionPane.showMessageDialog(this,
                    "ลบบัญชีที่กำลังใช้งานอยู่ไม่ได้",
                    "ลบไม่ได้", JOptionPane.WARNING_MESSAGE);
            return;
        }

        int choice = JOptionPane.showConfirmDialog(this,
                "ต้องการลบพนักงาน " + selectedName + " ใช่หรือไม่?",
                "ยืนยันการลบ", JOptionPane.YES_NO_OPTION, JOptionPane.QUESTION_MESSAGE);
        if (choice != JOptionPane.YES_OPTION) {
            return;
        }

        int deleted = employeeService.delete(id);
        if (deleted > 0) {
            showEmployees();
        } else {
            JOptionPane.showMessageDialog(this,
                    "ลบไม่สำเร็จ (อาจถูกลบไปก่อนแล้ว)",
                    "ลบไม่สำเร็จ", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnDeleteActionPerformed

    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        EmployeeDialog dialog = new EmployeeDialog(this, "เพิ่มพนักงานใหม่");
        dialog.setVisible(true);            // modal — โปรแกรมรอตรงนี้จนกว่า dialog จะถูกปิด
        if (dialog.isSaved()) {
            showEmployees();                // ข้อมูลเปลี่ยน → อ่านใหม่จากฐานข้อมูล
        }
    }//GEN-LAST:event_btnAddActionPerformed

    private void btnEditActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditActionPerformed
        int row = tblEmployee.getSelectedRow();
        if (row == -1) {
            JOptionPane.showMessageDialog(this,
                    "เลือกพนักงานในตารางก่อนกดแก้ไข",
                    "ยังไม่ได้เลือก", JOptionPane.WARNING_MESSAGE);
            return;
        }
        int id = (Integer) tblEmployee.getValueAt(row, 0);
        Employee emp = employeeService.get(id);
        if (emp == null) {
            JOptionPane.showMessageDialog(this,
                    "หาพนักงานรหัส " + id + " ไม่พบ (อาจถูกลบไปแล้ว)",
                    "ไม่พบข้อมูล", JOptionPane.ERROR_MESSAGE);
            return;
        }
        EmployeeDialog dialog = new EmployeeDialog(this, "แก้ไขพนักงาน: " + emp.getName(), emp);
        dialog.setVisible(true);
        if (dialog.isSaved()) {
            showEmployees();
        }
    }//GEN-LAST:event_btnEditActionPerformed

